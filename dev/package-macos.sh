#!/usr/bin/env bash
# Builds featherbittorrent for both Apple architectures and packages one universal .tar.gz, the archive
# the release page ships for macOS. Runs on macOS only: lipo, codesign and plutil are Apple's own tools.
# Both slices come from cargo build --locked --release, lipo joins them into the stage folder, lipo -archs
# reports what is really in the result, and codesign --verify checks the signature of the joined file. Apple
# Silicon runs nothing without a code signature, so an archive whose binary fails this check would fail at
# exec time on someone else's machine: whatever the linker left on the slices, one that verifies is shipped
# as built and one that does not is signed ad-hoc here and verified again. Notarizing needs an Apple Developer
# identity this repo does not have, and docs/install.md tells a browser downloader to clear the quarantine
# attribute. The man pages and completions come from the staged universal binary itself (generate-assets),
# gzipped here, so they cannot drift from the flags. The launchd example ships as documentation only, under
# examples/, never under /Library/LaunchAgents, and plutil -lint reads it back out of the finished archive.
# The last step is dev/smoke-cli.sh against a fresh extraction: what gets checked is the artifact a person
# downloads, not the build directory it came from. Nothing here contacts the network beyond cargo build.
# Usage: bash dev/package-macos.sh <version>   e.g. bash dev/package-macos.sh 0.1.0
# Output: target/dist/featherbittorrent-<version>-universal-apple-darwin.tar.gz and its .sha256, holding
#         featherbittorrent, LICENSE, NOTICE, README.md, man/, completions/, docs/autostart.md,
#         docs/server.md, docs/install.md (once that task writes it) and
#         examples/launchd/io.featherbit.featherbittorrent.plist.
set -euo pipefail

fail() { echo "package-macos.sh: $*" >&2; exit 1; }

# Arguments first, before any platform or tool question, so the refusals can be tested on any OS.
[[ $# -eq 1 ]] || fail "usage: bash dev/package-macos.sh <version>"
version="$1"
if ! [[ "$version" =~ ^[0-9]+\.[0-9]+\.[0-9]+([-+][0-9A-Za-z.-]+)?$ ]]; then
  fail "invalid version '$version' (expected X.Y.Z or X.Y.Z-pre)"
fi

[[ "$(uname -s)" == "Darwin" ]] || fail "package-macos.sh runs on macOS only"
for tool in cargo lipo codesign plutil shasum gzip; do
  command -v "$tool" >/dev/null || fail "package-macos.sh needs $tool"
done

root="$(cd "$(dirname "$0")/.." && pwd)"
cd "$root"
target="${CARGO_TARGET_DIR:-$root/target}"
dist="$root/target/dist"
targz="featherbittorrent-${version}-universal-apple-darwin"
stage="$dist/stage-macos-universal"
top="$stage/$targz"
assets="$stage/assets"
bin="$top/featherbittorrent"
plist="io.featherbit.featherbittorrent.plist"

# Both Apple architectures, the same lockfile and release profile as every other artifact. The runner is
# Apple silicon, so the smoke below runs the arm64 slice of what it builds; the x86_64 slice is checked by
# lipo -archs here and by the machine that downloads it.
for triple in aarch64-apple-darwin x86_64-apple-darwin; do
  cargo build --locked --release -p featherbittorrent --target "$triple"
done

rm -rf "$stage" "$dist/$targz.tar.gz" "$dist/$targz.tar.gz.sha256"
mkdir -p "$top"

# One binary with both architectures in it. chmod 755 because the archive has to carry the executable bit,
# and lipo's own output mode is not something to depend on.
lipo -create "$target/aarch64-apple-darwin/release/featherbittorrent" \
             "$target/x86_64-apple-darwin/release/featherbittorrent" \
             -output "$bin" || fail "lipo could not join the two builds into $bin"
chmod 755 "$bin"
if ! archs="$(lipo -archs "$bin")"; then fail "lipo -archs could not read $bin"; fi
if ! grep -qw arm64 <<<"$archs" || ! grep -qw x86_64 <<<"$archs"; then
  fail "$bin holds '$archs', expected both arm64 and x86_64"
fi
echo "ok: the staged binary holds arm64 and x86_64"

# The signature, on the joined file rather than on either slice: an ad-hoc signature is what Apple Silicon
# requires to run anything at all, and a broken one fails at exec time on someone else's machine.
if ! sign_out="$(codesign --verify "$bin" 2>&1)"; then
  echo "package-macos.sh: codesign --verify refused the joined binary ($sign_out); signing it ad-hoc" >&2
  codesign --force -s - "$bin" || fail "codesign --force -s - failed for $bin"
  sign_out="$(codesign --verify "$bin" 2>&1)" || fail "codesign --verify still refuses $bin: $sign_out"
fi
echo 'ok: codesign --verify accepts the staged binary'

# The man pages and completions, from the same clap Command as --help, generated by the artifact itself.
# gzip -9n leaves the page's own name and timestamp out of its header, so a page's bytes follow its text.
"$bin" generate-assets "$assets" >/dev/null || fail "generate-assets failed for $bin"
pages=("$assets"/man/*.1)
[[ -e "${pages[0]}" ]] || fail "generate-assets wrote no man pages under $assets/man"
for page in "${pages[@]}"; do
  gzip -9n "$page"
done
cp -R "$assets/man" "$top/man"
cp -R "$assets/completions" "$top/completions"

# The licenses, the docs and the launchd example. BSD install has no -D, so the folders come first.
mkdir -p "$top/docs" "$top/examples/launchd"
install -m 644 LICENSE "$top/LICENSE"
install -m 644 NOTICE "$top/NOTICE"
install -m 644 README.md "$top/README.md"
install -m 644 docs/autostart.md "$top/docs/autostart.md"
install -m 644 docs/server.md "$top/docs/server.md"
# The install guide is written by the task that documents the packages; ship it when it is there.
if [[ -f docs/install.md ]]; then
  install -m 644 docs/install.md "$top/docs/install.md"
fi
install -m 644 "packaging/launchd/$plist" "$top/examples/launchd/$plist"

# BSD tar has no --sort=name (GNU tar does), so the sorted file list is what makes the entry order depend
# on the tree rather than on how the filesystem happened to list it. --no-recursion keeps each listed path
# from being archived twice, once as itself and once as its parent's contents. The owner flags put 0 and
# root in every header instead of whoever ran this script; --no-acls, --no-fflags and --no-xattrs keep Apple
# metadata (an ACL from a copied file, a quarantine flag) out of a release archive; gzip -9n drops the name
# and timestamp it would otherwise store.
tar -C "$stage" --no-recursion --uid 0 --gid 0 --uname root --gname root \
    --no-acls --no-fflags --no-xattrs -cf - -T <(cd "$stage" && find "$targz" | LC_ALL=C sort) \
  | gzip -9n > "$dist/$targz.tar.gz"

# What a person unpacks, read back out of the finished archive.
if ! tar_files="$(tar -tzf "$dist/$targz.tar.gz" 2>&1)"; then
  fail "tar could not list $dist/$targz.tar.gz: $(head -1 <<<"$tar_files")"
fi
want_tar=(
  featherbittorrent LICENSE NOTICE README.md
  man/featherbittorrent.1.gz man/featherbittorrent-serve.1.gz
  completions/featherbittorrent.bash completions/_featherbittorrent completions/featherbittorrent.fish
  completions/_featherbittorrent.ps1
  docs/autostart.md docs/server.md
  "examples/launchd/$plist"
)
if [[ -f docs/install.md ]]; then want_tar+=(docs/install.md); fi
for f in "${want_tar[@]}"; do
  grep -qx "$targz/$f" <<<"$tar_files" || fail "the archive is missing $f: $(head -1 <<<"$tar_files") ..."
done

rm -rf "$stage"

# shasum prints `hash  name` with two spaces, the same shape sha256sum uses, so both `shasum -a 256 -c` and
# `sha256sum -c` read this file; the name in it is relative to target/dist, where the check is run from.
(cd "$dist" && shasum -a 256 "$targz.tar.gz" > "$targz.tar.gz.sha256") || fail "shasum failed in $dist"
if ! sum_out="$( (cd "$dist" && shasum -a 256 -c "$targz.tar.gz.sha256") 2>&1 )"; then
  fail "the .sha256 does not verify: $sum_out"
fi
echo "ok: shasum -a 256 -c accepts $targz.tar.gz.sha256"

# Everything after this reads the archive, not the build folder: two scratch directories, both removed on
# any exit, so a failing run leaves nothing behind but the artifact.
extract="$(mktemp -d)" || fail "could not make a temporary directory to extract into"
home="$(mktemp -d)" || { rm -rf "$extract"; fail "could not make a scratch home for the smoke"; }
trap 'rm -rf "$extract" "$home"' EXIT
tar -xzf "$dist/$targz.tar.gz" -C "$extract" || fail "tar could not extract $dist/$targz.tar.gz"

# The plist as the archive carries it: an example in examples/, nothing this archive installs or starts.
plutil -lint "$extract/$targz/examples/launchd/$plist" >/dev/null \
  || fail "plutil -lint refused examples/launchd/$plist as archived"
echo "ok: plutil -lint accepts examples/launchd/$plist"

# The same smoke every other artifact passes through, on the binary this archive shipped. It is what checks
# the version, so a mismatch here means the artifact and the release disagree, not that cargo built wrong.
bash dev/smoke-cli.sh "$extract/$targz/featherbittorrent" "$version" "$home"

echo "$dist/$targz.tar.gz"
cat "$dist/$targz.tar.gz.sha256"

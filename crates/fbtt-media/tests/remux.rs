/// H.264 from `h264-aac-opus-srt-ass.mkv` at 0 ms: the total sample count
/// equals the frame count in `expected.json`, `start_ms()` is 0, every
/// fragment starts with a sync sample, and `dts + cts - offset` over all
/// samples, sorted, equals the source PTS list - reconstructed from the
/// fragments' own `tfdt`, durations and composition offsets.
#[test]
fn remux_video_from_start() {
    let file = fixture_bytes(MKV);
    let count = expected_frame_count(MKV, 1);
    let oracle = oracle_stream(&file, 1, None);

    let mut source =
        open_track(Cursor::new(file.clone()), 1, 0).expect("the video track opens at 0");
    assert_eq!(source.config().kind, TrackKind::Video, "track 1 is video");
    let samples = drain_samples(&mut source);
    let kept = source_kept_video(&oracle);
    assert_eq!(
        samples.len(),
        kept.len(),
        "the source is the demuxer's own frame stream under the crate's keep rule"
    );
    assert_eq!(
        samples.len(),
        count,
        "the sample count is the frame count in expected.json"
    );
    for ((sync, frame), sample) in kept.iter().zip(&samples) {
        assert_eq!(
            sample.pts,
            i64::try_from(frame.timestamp * u64::from(VIDEO_TIMESCALE) / 1_000)
                .expect("a fixture PTS"),
            "track 1 PTS matches the demuxer's own frame stream"
        );
        assert_eq!(&sample.data, &frame.data, "bytes pass through unchanged");
        assert_eq!(
            sample.keyframe, *sync,
            "the sync flag follows the frame's flags through the crate's reading"
        );
    }

    let stream = FragmentStream::new(open_track(Cursor::new(file), 1, 0).expect("opens again"))
        .expect("a stream");
    let mut stream = stream;
    assert_eq!(stream.start_ms(), 0, "start_ms() is 0 for a zero start");
    let fragments = drain_fragments(&mut stream);
    assert!(
        !fragments.is_empty(),
        "a stream with samples emits fragments"
    );

    // The fragments' own timeline: tfdt is the moof's first decode time (with
    // the plan's 1000 ms offset baked in), each later decode time is the last
    // plus the durations the trun states, and a sample's PTS is its decode
    // time plus its signed composition offset. Subtract the offset, sort, and
    // the result must be the container's PTS list - the same identity
    // `dts_synthesis_with_b_frames` checks writer-side, checked here through
    // the bytes a player actually receives.
    let offset_ticks = i64::try_from(TIME_OFFSET_MS * u64::from(VIDEO_TIMESCALE) / 1_000)
        .expect("the offset in ticks");
    let mut rebuilt: Vec<i64> = Vec::new();
    let moofs = all_moofs(&fragments);
    for (number, traf) in moofs.iter().enumerate() {
        assert_eq!(
            traf.trun_flags[0] & 0x0200_0000,
            0x0200_0000,
            "fragment {number} starts with a sync sample"
        );
        let mut dts = i64::try_from(traf.tfdt_base).expect("tfdt fits i64");
        for position in 0..traf.trun_count as usize {
            rebuilt.push(dts + traf.trun_cts[position] - offset_ticks);
            dts += i64::from(traf.trun_durations[position]);
        }
    }
    assert_eq!(
        streamed_sample_count(&fragments),
        count,
        "the fragments carry exactly the track's samples"
    );
    let first = boxes(&fragments[0]);
    assert_eq!(
        &first[0].kind, b"ftyp",
        "the first Vec starts with the init segment"
    );
    rebuilt.sort_unstable();
    let mut source_pts: Vec<i64> = oracle
        .iter()
        .map(|frame| {
            i64::try_from(frame.timestamp * u64::from(VIDEO_TIMESCALE) / 1_000)
                .expect("a fixture PTS")
        })
        .collect();
    source_pts.sort_unstable();
    assert_eq!(
        rebuilt, source_pts,
        "dts + cts - offset over all samples, sorted, is the source PTS list"
    );
}


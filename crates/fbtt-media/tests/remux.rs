/// A truncated file answers with a verdict, never a panic: a stream that
/// opened before the cut yields some fragments and then `Err`; a cut that
/// lands where the open itself needs bytes the file no longer has refuses at
/// open, which is also `Err`. Measured: 60% of `h264-aac-opus-srt-ass.mkv`
/// refuses at open (its segment header and `SeekHead` promise elements the cut
/// removed), while 60% of the cue-less fixture streams and then errors. And a
/// synthetic file whose first block declares 4096 bytes and holds 40 is the
/// same shape one element deep - a stream that stops inside data it promised
/// is a verdict, not a crash.
#[test]
fn remux_truncated_file_ends_with_an_error() {
    let whole = fixture_bytes(MKV);
    let live = fixture_bytes(LIVE);
    // (label, bytes, fraction). Every case must answer with a verdict.
    for (label, bytes, fraction) in [
        ("fixture at 60%", &whole, 3usize * 100 / 5),
        ("fixture at 85%", &whole, 17 * 5),
        ("nocues fixture at 60%", &live, 3 * 20),
    ] {
        let cut = bytes.len() * fraction / 100;
        let verdict = match open_track(Cursor::new(bytes[..cut].to_vec()), 1, 0) {
            Ok(mut stream) => {
                let mut fragments = 0usize;
                let mut ended_cleanly = false;
                let mut error_message = String::new();
                loop {
                    match stream.next_fragment() {
                        Ok(Some(_)) => fragments += 1,
                        Ok(None) => {
                            ended_cleanly = true;
                            break;
                        }
                        Err(error) => {
                            error_message = error.to_string();
                            break;
                        }
                    }
                }
                if label == "nocues fixture at 60%" {
                    assert!(
                        fragments > 0,
                        "{label}: the cut is past several GOPs, fragments must have streamed first"
                    );
                    assert!(
                        !ended_cleanly,
                        "{label}: the cut sits inside cluster data the header promised, so the \
                         stream must end with an error, not cleanly"
                    );
                }
                if ended_cleanly {
                    format!("streamed {fragments} fragments, then a clean end")
                } else {
                    format!("streamed {fragments} fragments, then {error_message}")
                }
            }
            Err(error) => error.to_string(),
        };
        // Every branch above is a real answer: fragments then an error,
        // fragments then a clean end, or a refusal at open. Anything else
        // (including a panic, which would have failed the test outright)
        // cannot reach here.
        assert!(
            verdict.contains("fragments") || verdict.contains("malformed"),
            "{label}: answered {verdict:?}, which is neither a stream nor a refusal"
        );
        if label == "fixture at 60%" {
            // Measured: this cut removes elements the segment header promises,
            // so the open itself says so instead of streaming first.
            assert!(
                verdict.starts_with("malformed"),
                "{label}: expected the open to refuse, got {verdict:?}"
            );
        }
    }

    // The synthetic overrun must produce an error too: its declared block size
    // is a promise the stream does not keep, and that is the definition of a
    // malformed stream.
    let tracks = ebml(
        &TRACKS,
        &[track_element(
            1,
            1,
            H264_ID,
            Some(avcc().as_slice()),
            None,
            Some((640, 360)),
            None,
            None,
        )]
        .concat(),
    );
    let short_block = ebml_declaring(
        &SIMPLE_BLOCK,
        4096,
        &[0x81u8, 0x00, 0x00, 0x80, 0x41, 0x01, 0x02, 0x03],
    );
    let clusters = vec![ebml(
        &CLUSTER,
        &[ebml(&TIMECODE, &0u64.to_be_bytes()), short_block].concat(),
    )];
    let truncated = matroska_file(&indexed_segment(&tracks, 1_000_000, &clusters));
    let mut stream = open_track(Cursor::new(truncated), 1, 0)
        .expect("the header parses; the overrun is downstream");
    match stream.next_fragment() {
        Ok(maybe) => panic!("a block that overruns the stream ended as {maybe:?}, not an error"),
        Err(error) => assert!(
            matches!(error, MediaError::Malformed(_) | MediaError::Io(_)),
            "the overrun is a verdict, not a panic: {error:?}"
        ),
    }
}

/// A video track whose frames are all SimpleBlocks without the keyframe flag
/// (100 001 of them - more than the walk bound of `MAX_SKIPPED_FRAMES`,
/// chunked into 25k-frame clusters because a block's relative timecode is an
/// i16) gives `Err(Malformed)`: without the bound one pull would walk the
/// whole file looking for a keyframe that never arrives. The audio direction
/// gets the same bound from the other side: frames dropped for sitting before
/// a start time count too, and a backwards-running cluster tail gives up with
/// the same verdict after the first real sample arrives.
#[test]
fn remux_without_any_keyframe_gives_up() {
    let video_tracks = ebml(
        &TRACKS,
        &[track_element(
            1,
            1,
            H264_ID,
            Some(avcc().as_slice()),
            None,
            Some((640, 360)),
            None,
            None,
        )]
        .concat(),
    );
    let mut clusters = Vec::new();
    let mut total = 0;
    while total < 100_001 {
        let chunk = 25_000u16;
        let blocks: Vec<Vec<u8>> = (0..chunk)
            .map(|frame| {
                simple_block(
                    1,
                    i16::try_from(frame).expect("a chunk under i16"),
                    false,
                    &[0x41],
                )
            })
            .collect();
        clusters.push(cluster(total, &blocks));
        total += u64::from(chunk);
    }
    let video = matroska_file(&indexed_segment(&video_tracks, 1_000_000, &clusters));
    let mut stream = open_track(Cursor::new(video), 1, 0).expect("the header is fine");
    match stream.next_fragment() {
        Err(MediaError::Malformed(message)) => assert!(
            message.contains("too many frames without a sample"),
            "the walk gave up with the verdict it means: {message}"
        ),
        other => panic!("100k non-sync frames before any keyframe is a verdict, got {other:?}"),
    }
    // The audio direction. The cluster at 500000 ms starts below the start
    // time and counts upwards across it, so the source's own drop rule passes
    // over the frames below and then emits an ascending run long enough to
    // seal and emit real fragments; the clusters behind it (unsorted in time,
    // and with no cue table for the seek to get lost in) are all below the
    // start time again. Fragments arrive, and then the walk drops more than
    // the bound of frames before it gives up mid-tail.
    let audio_tracks = ebml(
        &TRACKS,
        &[track_element(
            2,
            2,
            MP3_ID,
            None,
            Some((44100.0, 2)),
            None,
            None,
            None,
        )]
        .concat(),
    );
    let mut audio_clusters = vec![
        cluster(0, &[simple_block(2, 0, false, &[0xFF, 0xFB, 0x90, 0x64])]),
        cluster(
            350_000,
            &[simple_block(2, 0, false, &[0xFF, 0xFB, 0x90, 0x64])],
        ),
    ];
    let counted: Vec<Vec<u8>> = (0..25_001u16)
        .map(|frame| {
            let offset =
                i16::try_from(i32::from(frame) - 15_000).expect("an i16 relative timecode");
            simple_block(2, offset, false, &[0xFF, 0xFB, 0x90, 0x64])
        })
        .collect();
    audio_clusters.push(cluster(500_000, &counted));
    for tail in 0..5u64 {
        let blocks: Vec<Vec<u8>> = (0..25_001i16)
            .map(|frame| simple_block(2, frame, false, &[0xFF, 0xFB, 0x90, 0x64]))
            .collect();
        audio_clusters.push(cluster(100_000 + tail * 50_000, &blocks));
    }
    // No SeekHead and no Cues: the seek falls back to the cluster walk, and
    // either landing - the cluster at the target or the one below it - puts
    // the backwards cluster's tail and the unsorted clusters behind it in the
    // source's way, which is the point.
    let mut segment = audio_tracks;
    segment.extend_from_slice(&info_element(1_000_000));
    for cluster in &audio_clusters {
        segment.extend_from_slice(cluster);
    }
    let before = matroska_file(&segment);
    let mut stream =
        open_track(Cursor::new(before), 2, 500_000).expect("the start time is expressible");
    let mut fragments: Vec<Vec<u8>> = Vec::new();
    let verdict = loop {
        match stream.next_fragment() {
            Ok(Some(fragment)) => fragments.push(fragment),
            Ok(None) => break "clean end of stream".to_string(),
            Err(error) => break error.to_string(),
        }
    };
    let samples = streamed_samples(&fragments);
    let first = samples
        .first()
        .expect("a frame exists at or after the start time");
    assert_eq!(
        first.pts,
        500_000 * 44_100 / 1_000,
        "the first frame at or after the start time is the one the seek landed on"
    );
    // The bound then trips mid-walk, on a later fragment call: the frames
    // between the landing cluster's kept run and the end of the stream all
    // sit before the start time, and there are more than the bound of them.
    assert!(
        verdict.contains("too many frames without a sample"),
        "the walk gave up with the verdict it means: {verdict}"
    );
}

/// The header budget decision's test: a Matroska in memory with one video
/// track, a SeekHead, 60 000 CuePoints and tiny clusters. `MatroskaFile::open`
/// parses the whole table (its SeekHead names `Cues`), and the walk costs a
/// dozen-plus reader calls an entry - measured, not estimated - so the file
/// needs a header budget an order of magnitude above what a thousand-entry
/// table costs. That is the `MAX_HEADER_OPS` raise this fixture exists to
/// prove.
#[test]
fn open_track_with_60000_cue_points() {
    let tracks = ebml(
        &TRACKS,
        &[track_element(
            1,
            1,
            H264_ID,
            Some(avcc().as_slice()),
            None,
            Some((640, 360)),
            None,
            None,
        )]
        .concat(),
    );
    let info = info_element(1_000_000);
    let flat_clusters: Vec<Vec<u8>> = (0..40u64)
        .map(|second| {
            cluster(
                second * 1_000,
                &[simple_block(1, 0, true, &[0x41, 0x01, 0x02, 0x03])],
            )
        })
        .collect();

    // Layout: head, tracks, info, clusters..., cues - the head names all four
    // element kinds, with the clusters named at their first.
    let names: Vec<&[u8]> = vec![&TRACKS, &INFO, &CLUSTER, &CUES];
    let placeholder = seek_head_named(&names.iter().map(|id| (*id, 0u64)).collect::<Vec<_>>());
    let tracks_at = u64::try_from(placeholder.len()).expect("a SeekHead under 4 GiB");
    let info_at = tracks_at + u64::try_from(tracks.len()).expect("Tracks under 4 GiB");
    let cluster_at = info_at + u64::try_from(info.len()).expect("Info under 4 GiB");
    let clusters_len: usize = flat_clusters.iter().map(Vec::len).sum();
    let cues_at = cluster_at + u64::try_from(clusters_len).expect("clusters under 4 GiB");

    let head = seek_head_named(
        &names
            .iter()
            .enumerate()
            .map(|(index, id)| (*id, [tracks_at, info_at, cluster_at, cues_at][index]))
            .collect::<Vec<_>>(),
    );
    assert_eq!(head.len(), placeholder.len());

    let mut cue_body = Vec::new();
    for second in 0..60_000u64 {
        let positions = ebml(
            &CUE_TRACK_POSITIONS,
            &[
                ebml(&CUE_TRACK, &[1]),
                ebml(&CUE_CLUSTER_POSITION, &cluster_at.to_be_bytes()),
            ]
            .concat(),
        );
        cue_body.extend_from_slice(&ebml(
            &CUE_POINT,
            &[ebml(&CUE_TIME, &(second * 1_000).to_be_bytes()), positions].concat(),
        ));
    }
    let cues = ebml(&CUES, &cue_body);

    let mut segment = head;
    segment.extend_from_slice(&tracks);
    segment.extend_from_slice(&info);
    for cluster in &flat_clusters {
        segment.extend_from_slice(cluster);
    }
    segment.extend_from_slice(&cues);
    let file = matroska_file(&segment);

    // The decision's assertion, exactly: a file this indexed opens from zero.
    let mut fresh = open_track(Cursor::new(file.clone()), 1, 0)
        .unwrap_or_else(|error| panic!("open_track refused a 60000-entry cue table at 0: {error}"));
    let fragments = drain_fragments(&mut fresh);
    assert_eq!(
        streamed_sample_count(&fragments),
        40,
        "and its whole cluster stream transfers from zero"
    );

    let calls = Arc::new(AtomicU64::new(0));
    let counting = CountCalls {
        inner: Cursor::new(file),
        calls: Arc::clone(&calls),
    };
    // The seek to 30000 seconds: broad phase is a search through the 60000
    // cue entries, and narrow phase walks the cluster headers between the
    // landing cluster and the target to find the first frame at or after it.
    // That is real cost on reader calls, which is what the budget assertions
    // measure right after the open.
    let mut stream = match open_track(counting, 1, 30_000) {
        Ok(stream) => stream,
        Err(error) => panic!("open_track refused a 60000-entry cue table: {error}"),
    };
    let opened_with = calls.load(Ordering::Relaxed);
    assert!(
        opened_with > 1 << 20,
        "the fixture must actually be long: {opened_with} reader calls, which is not over the old budget"
    );
    assert!(
        opened_with < 1 << 22,
        "the fixture must fit the raised budget: {opened_with} reader calls"
    );
    let fragments = drain_fragments(&mut stream);
    let samples = streamed_samples(&fragments);
    // The seek landed on 30 seconds: the source kept the keyframes at or after
    // where its own seek clamped (all 40 frames are keyframes, from 30 s on
    // that is 10 of them).
    assert_eq!(
        samples.len(),
        10,
        "the 30000 s seek lands inside the last 10 seconds"
    );
    assert_eq!(
        samples[0].pts,
        30_000 * 90,
        "first sample PTS at 30 s on the 90 kHz timeline"
    );
}

/// A cue whose cluster is real but whose `CueRelativePosition` is
/// `0xFFFF_FFFF_FFFF_FFF0`: `seek` adds it to the cluster's data offset.
/// Upstream 0.8.1 overflowed a `u64` right there and, in a debug build,
/// panicked (its broad phase, `cluster_data_offset + relative_position`); the
/// pinned featherbit fork overflow-checks the cue arithmetic - a relative
/// position outside a cluster of known size is clamped to the cue's own
/// cluster start, and the narrow phase walks forward from there (the fork's
/// `seek_broad_phase`). The only block here is at 0 ms and the target is
/// 500_000 ms, so the forward walk returns nothing: the stream ends with
/// nothing to play (just the init segment and `None`) and `start_ms()` stays
/// the requested time. The open and drain still run in a thread with a five
/// second bound: a library that crashes or hangs on hostile remote input is
/// a crashed API worker, and the crate keeps its catch-unwind guard around
/// the seek whatever the demuxer does.
#[test]
fn remux_cue_past_end_is_an_error() {
    let tracks = ebml(
        &TRACKS,
        &[track_element(
            1,
            1,
            H264_ID,
            Some(avcc().as_slice()),
            None,
            Some((640, 360)),
            None,
            None,
        )]
        .concat(),
    );
    let info = info_element(1_000_000);
    let cluster = cluster(0, &[simple_block(1, 0, true, &[0x41, 0x01])]);

    let names: Vec<&[u8]> = vec![&TRACKS, &INFO, &CLUSTER, &CUES];
    let placeholder = seek_head_named(&names.iter().map(|id| (*id, 0u64)).collect::<Vec<_>>());
    let tracks_at = u64::try_from(placeholder.len()).expect("a SeekHead under 4 GiB");
    let info_at = tracks_at + u64::try_from(tracks.len()).expect("Tracks under 4 GiB");
    let cluster_at = info_at + u64::try_from(info.len()).expect("Info under 4 GiB");
    let cues_at = cluster_at + u64::try_from(cluster.len()).expect("Cluster under 4 GiB");
    let head = seek_head_named(
        &names
            .iter()
            .enumerate()
            .map(|(index, id)| (*id, [tracks_at, info_at, cluster_at, cues_at][index]))
            .collect::<Vec<_>>(),
    );

    let positions = ebml(
        &CUE_TRACK_POSITIONS,
        &[
            ebml(&CUE_TRACK, &[1]),
            ebml(&CUE_CLUSTER_POSITION, &cluster_at.to_be_bytes()),
            ebml(
                &CUE_RELATIVE_POSITION,
                &0xFFFF_FFFF_FFFF_FFF0u64.to_be_bytes(),
            ),
        ]
        .concat(),
    );
    let point = ebml(
        &CUE_POINT,
        &[ebml(&CUE_TIME, &500_000u64.to_be_bytes()), positions].concat(),
    );
    let cues = ebml(&CUES, &[point].concat());

    let mut segment = head;
    segment.extend_from_slice(&tracks);
    segment.extend_from_slice(&info);
    segment.extend_from_slice(&cluster);
    segment.extend_from_slice(&cues);
    let file = matroska_file(&segment);

    let (sender, receiver) = std::sync::mpsc::channel();
    thread::spawn(move || {
        let outcome = match open_track(Cursor::new(file), 1, 500_000) {
            Ok(mut stream) => {
                // Open survived: the stream then either errors or ends. A
                // wrapped panic surfaces here as an error; a clean end (the
                // clamped walk forward from the cue's cluster finding no
                // block at or after 500_000 ms) is also an acceptable
                // answer - but fragments are only counted when they carry a
                // sample, so the init segment alone is a clean end and a
                // mis-landing that streamed this file's one block is not.
                let mut parts = 0;
                let mut verdict = "clean end of stream".to_string();
                loop {
                    match stream.next_fragment() {
                        Ok(Some(fragment)) => {
                            if find_box(&boxes(&fragment), b"moof").is_some() {
                                parts += 1;
                            }
                        }
                        Ok(None) => break,
                        Err(error) => {
                            verdict = error.to_string();
                            break;
                        }
                    }
                }
                if parts > 0 {
                    verdict = format!(
                        "{parts} fragments with samples streamed, which is not a stream from past the end"
                    );
                }
                verdict
            }
            Err(error) => error.to_string(),
        };
        let _ = sender.send(outcome);
    });
    let outcome = match receiver.recv_timeout(Duration::from_secs(5)) {
        Ok(outcome) => outcome,
        Err(std::sync::mpsc::RecvTimeoutError::Timeout) => {
            panic!("seeking to a cue past the end hung instead of answering")
        }
        Err(std::sync::mpsc::RecvTimeoutError::Disconnected) => {
            panic!("the seek panicked out of its guard instead of reporting a verdict")
        }
    };
    // The fork's documented answer here is the clean empty end; any refusal
    // (a Malformed verdict at open or in the stream) is also a verdict.
    // "Panicked" or "hung" would have reached us as a disconnect or a
    // timeout above, and a mis-landing that streamed the 0 ms block fails
    // the moof count inside the verdict string.
    assert!(
        outcome.contains("malformed") || outcome.contains("clean end of stream"),
        "a cue past the end answered {outcome:?}, which is neither a Malformed verdict nor a clean end"
    );
}

/// The plan's byte-accounting rule, measured against a raw `File` (no
/// buffering in front of it, so every byte the demuxer asks for is counted as
/// it crosses): seeking the cluster table costs *seeks*, and block bodies are
/// read whole, so a whole-file stream costs about one file pass plus the
/// header elements it re-reads - never the quadratic re-reading a buffering
/// mistake would cost. Two passes is the bound; a `BufReader` with a big
/// buffer in front of the seeking demuxer re-reads kilobytes per seek and
/// would blow it.
#[test]
fn remux_reads_each_byte_about_once() {
    let path = fixture_path(MKV);
    let bytes = Arc::new(AtomicU64::new(0));
    let counting = CountingReader {
        inner: File::open(&path).expect("fixture"),
        bytes: Arc::clone(&bytes),
    };
    let file_size = counting.inner.metadata().expect("metadata").len();
    let mut stream = open_track(counting, 1, 0).expect("the video track opens");
    let fragments = drain_fragments(&mut stream);
    assert_eq!(
        streamed_sample_count(&fragments),
        expected_frame_count(MKV, 1),
        "the whole video track streamed"
    );
    let total = bytes.load(Ordering::Relaxed);
    assert!(
        total <= file_size * 2,
        "streamed a {file_size} byte file while reading {total} bytes"
    );
}


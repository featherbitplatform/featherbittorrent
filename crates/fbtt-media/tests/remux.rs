/// A `SimpleBlock` for track `track`, `offset` scale-units after its cluster's
/// timecode. Track 1..9 are one-byte VINTs; the keyframe flag is the flag
/// byte's high bit, and lacing bits stay 0 (a plain single-frame block).
fn simple_block(track: u64, offset: i16, keyframe: bool, payload: &[u8]) -> Vec<u8> {
    let flags = if keyframe { 0x80 } else { 0x00 };
    ebml(
        &SIMPLE_BLOCK,
        &[
            vec![0x80 | u8::try_from(track).expect("a small track number")],
            offset.to_be_bytes().to_vec(),
            vec![flags],
            payload.to_vec(),
        ]
        .concat(),
    )
}

/// A fixed-laced `SimpleBlock`: `frames` frames of `size` bytes each, all
/// sharing the block's timestamp. Lacing is the flag byte's bits 1-2 (2 is
/// fixed-size), and this demuxer's fixed-size lacing states the number of
/// frames minus one in one byte after the flags and divides the block's data
/// evenly between them - which is how `matroska-demuxer` 0.8.1 reads the
/// lacing value, and the shape the frames below are checked against.
fn laced_simple_block(track: u64, offset: i16, frames: usize, size: usize) -> Vec<u8> {
    let mut body = Vec::new();
    body.push(0x80 | u8::try_from(track).expect("a small track number"));
    body.extend_from_slice(&offset.to_be_bytes());
    body.push(0x84); // keyframe set, lacing value 2 (fixed) in bits 1-2
    body.push(u8::try_from(frames - 1).expect("a small lace"));
    for _ in 0..frames {
        body.extend_from_slice(&vec![0x55; size]);
    }
    ebml(&SIMPLE_BLOCK, &body)
}

/// A `BlockGroup` - the shape that carries a `BlockDuration`, and whose `Block`
/// the demuxer reports with no keyframe flag at all.
fn block_group(track: u64, offset: i16, duration: u64, payload: &[u8]) -> Vec<u8> {
    ebml(
        &BLOCK_GROUP,
        &[
            ebml(
                &BLOCK,
                &[
                    vec![0x80 | u8::try_from(track).expect("a small track number")],
                    offset.to_be_bytes().to_vec(),
                    vec![0x00],
                    payload.to_vec(),
                ]
                .concat(),
            ),
            ebml(&BLOCK_DURATION, &duration.to_be_bytes()),
        ]
        .concat(),
    )
}

/// A `BlockGroup` holding no `Block` at all: two bytes the demuxer walks into,
/// reports as read, and fills nothing with.
fn empty_block_group() -> Vec<u8> {
    vec![0xA0, 0x80]
}

fn cluster(timecode_ms: u64, blocks: &[Vec<u8>]) -> Vec<u8> {
    let mut body = ebml(&TIMECODE, &timecode_ms.to_be_bytes());
    for block in blocks {
        body.extend_from_slice(block);
    }
    ebml(&CLUSTER, &body)
}

fn seek_entry(id: &[u8], at: u64) -> Vec<u8> {
    ebml(
        &SEEK,
        &[ebml(&SEEK_ID, id), ebml(&SEEK_POSITION, &at.to_be_bytes())].concat(),
    )
}

fn seek_head_named(entries: &[(&[u8], u64)]) -> Vec<u8> {
    let body: Vec<u8> = entries
        .iter()
        .flat_map(|(id, at)| seek_entry(id, *at))
        .collect();
    ebml(&SEEK_HEAD, &body)
}

/// A `Segment` body laid out as head, tracks, info, then the clusters: the
/// `SeekHead` names the first cluster (and the cues, if given) so `open`
/// indexes like a real file instead of walking the whole stream.
///
/// The head is built once with placeholder offsets to learn its length, then
/// again with the real ones; all elements after it sit at known offsets because
/// everything ahead of them is already assembled.
fn indexed_segment(tracks: &[u8], scale: u64, clusters: &[Vec<u8>]) -> Vec<u8> {
    let info = info_element(scale);
    let names: Vec<&[u8]> = vec![&TRACKS, &INFO, &CLUSTER];
    let placeholder = seek_head_named(&names.iter().map(|id| (*id, 0u64)).collect::<Vec<_>>());
    let tracks_at = u64::try_from(placeholder.len()).expect("a SeekHead under 4 GiB");
    let info_at = tracks_at + u64::try_from(tracks.len()).expect("Tracks under 4 GiB");
    let cluster_at = info_at + u64::try_from(info.len()).expect("Info under 4 GiB");

    let head = seek_head_named(
        &names
            .iter()
            .enumerate()
            .map(|(index, id)| match index {
                0 => (*id, tracks_at),
                1 => (*id, info_at),
                _ => (*id, cluster_at),
            })
            .collect::<Vec<_>>(),
    );
    assert_eq!(head.len(), placeholder.len());
    let mut body = head;
    body.extend_from_slice(tracks);
    body.extend_from_slice(&info);
    for cluster in clusters {
        body.extend_from_slice(cluster);
    }
    body
}

/// The GOP file every fragment-level test reads: a 90 kHz video track and four
/// clusters of 25 frames at 40 ms, each cluster opening with a keyframe - so
/// keyframes at 0, 1000, 2000 and 3000 ms, matching the real fixture's pattern
/// at a scale the test can type out. 100 frames, 4 seconds.
fn gop_file() -> Vec<u8> {
    let tracks = ebml(
        &TRACKS,
        &[track_element(
            1,
            1,
            H264_ID,
            Some(avcc().as_slice()),
            None,
            Some((640, 360)),
            None,
            None,
        )]
        .concat(),
    );
    let mut clusters = Vec::new();
    for gop in 0..4u64 {
        let mut blocks = Vec::new();
        for frame in 0..25u16 {
            blocks.push(simple_block(
                1,
                (frame * 40) as i16,
                frame == 0,
                &[0x41, 0x01, 0x02, 0x03],
            ));
        }
        clusters.push(cluster(gop * 1000, &blocks));
    }
    matroska_file(&indexed_segment(&tracks, 1_000_000, &clusters))
}

// ---------------------------------------------------------------------------
// A minimal fragmented-MP4 reader, for reading back what the writer wrote.
// `mp4_atom` models the boxes it parses, but a fragment arrives as bytes from
// the stream, and the fields these tests check (tfdt's base decode time, trun's
// count, durations, sizes, composition offsets and flags) are read field by
// field here rather than through a model that could be as wrong as the writer.
// ---------------------------------------------------------------------------

struct Mp4Box<'a> {
    kind: [u8; 4],
    body: &'a [u8],
}

fn boxes(mut bytes: &[u8]) -> Vec<Mp4Box<'_>> {
    let mut out = Vec::new();
    while !bytes.is_empty() {
        assert!(bytes.len() >= 8, "a box is at least its header");
        let size = u32::from_be_bytes([bytes[0], bytes[1], bytes[2], bytes[3]]) as usize;
        assert!(size >= 8 && size <= bytes.len(), "a box fits its bytes");
        out.push(Mp4Box {
            kind: [bytes[4], bytes[5], bytes[6], bytes[7]],
            body: &bytes[8..size],
        });
        bytes = &bytes[size..];
    }
    out
}

fn find_box<'a>(boxes: &[Mp4Box<'a>], kind: &[u8; 4]) -> Option<&'a [u8]> {
    boxes
        .iter()
        .find(|entry| &entry.kind == kind)
        .map(|entry| entry.body)
}

/// Descend the init segment's container boxes (`moov` and inwards) looking for
/// one kind of box.
fn deep_find<'a>(bytes: &'a [u8], kind: &[u8; 4]) -> Option<&'a [u8]> {
    let containers: [[u8; 4]; 5] = [*b"moov", *b"trak", *b"mdia", *b"minf", *b"stbl"];
    for entry in boxes(bytes) {
        if &entry.kind == kind {
            return Some(entry.body);
        }
        if containers.contains(&entry.kind)
            && let Some(found) = deep_find(entry.body, kind)
        {
            return Some(found);
        }
    }
    None
}

/// The fourcc of the first sample entry in the init segment's `stsd`: the
/// codec identity a browser will see (`avc1`, `hvc1`, `av01`, `mp4a`, ...).
fn sample_entry_fourcc(bytes: &[u8]) -> [u8; 4] {
    let stsd = deep_find(bytes, b"stsd").expect("an stsd in the init segment");
    // The body of a fullbox (after size and type) starts with version and
    // flags (4); `stsd` then carries reserved (4) and sample_count (4), and
    // each entry starts with size (4) and its fourcc (4).
    let fourcc = &stsd[12..16];
    [fourcc[0], fourcc[1], fourcc[2], fourcc[3]]
}

/// The handler fourcc from the init segment's `hdlr`: `vide` or `soun`, the
/// kind the stream says it is, read off the bytes rather than off a config
/// struct the public API does not hand out.
fn track_handler(init: &[u8]) -> [u8; 4] {
    let hdlr = deep_find(init, b"hdlr").expect("an hdlr in the init segment");
    // A fullbox's body starts with version and flags (4), then the pre-defined
    // word (4), and then the handler's own fourcc.
    let fourcc = &hdlr[8..12];
    [fourcc[0], fourcc[1], fourcc[2], fourcc[3]]
}

/// The timeline's ticks-per-second, straight from the init segment's `mvhd`.
/// The offset the wire times carry is measured in this unit, so rebuilding a
/// timeline asks the stream, not a constant a fixture might not keep.
fn init_timescale(fragments: &[Vec<u8>]) -> u32 {
    let mvhd = deep_find(&fragments[0], b"mvhd").expect("an mvhd in the init segment");
    // Body order: version and flags (4), creation and modification time -
    // four bytes each in a version 0 box, eight each in the version 1 box this
    // writer produces - and then timescale.
    let at = match mvhd[0] {
        0 => 12,
        1 => 20,
        other => panic!("mvhd version {other}"),
    };
    u32::from_be_bytes([mvhd[at], mvhd[at + 1], mvhd[at + 2], mvhd[at + 3]])
}

/// The `traf` inside the first `moof` of a fragment, and its `tfdt` base media
/// decode time plus its `trun`'s sample count, durations, sizes, composition
/// offsets and flags.
struct Traf {
    tfdt_base: u64,
    trun_count: u32,
    trun_durations: Vec<u32>,
    trun_sizes: Vec<u32>,
    trun_cts: Vec<i64>,
    trun_flags: Vec<u32>,
}

fn read_first_traf(fragment: &[u8]) -> Traf {
    let fragment_boxes = boxes(fragment);
    let moof = find_box(&fragment_boxes, b"moof").expect("a moof in a fragment");
    let moof_boxes = boxes(moof);
    let traf = find_box(&moof_boxes, b"traf").expect("a traf in a moof");
    let traf_boxes = boxes(traf);
    let tfdt = find_box(&traf_boxes, b"tfdt").expect("a tfdt in a traf");
    let version = tfdt[0];
    let tfdt_base = match version {
        0 => u64::from(u32::from_be_bytes([tfdt[4], tfdt[5], tfdt[6], tfdt[7]])),
        1 => u64::from_be_bytes([
            tfdt[4], tfdt[5], tfdt[6], tfdt[7], tfdt[8], tfdt[9], tfdt[10], tfdt[11],
        ]),
        other => panic!("tfdt version {other}"),
    };
    let trun = find_box(&traf_boxes, b"trun").expect("a trun in a traf");
    let version = trun[0];
    assert_eq!(version, 1, "a fragmented stream writes trun version 1");
    let flags = u32::from_be_bytes([0, trun[1], trun[2], trun[3]]);
    let count = u32::from_be_bytes([trun[4], trun[5], trun[6], trun[7]]);
    let mut rest = &trun[8..];
    if flags & 0x1 != 0 {
        rest = &rest[4..]; // data_offset
    }
    // `first_sample_flags`: the single-sample-fragment shape. `mp4_atom` hoists
    // a fragment's sample flags there when only its first sample has any, which
    // for this writer means exactly the one-sample fragments; the per-sample
    // flags field is then absent and the first entry inherits from here.
    let first_flags = if flags & 0x4 != 0 {
        let value = u32::from_be_bytes([rest[0], rest[1], rest[2], rest[3]]);
        rest = &rest[4..];
        Some(value)
    } else {
        None
    };
    let mut durations = Vec::new();
    let mut sizes = Vec::new();
    let mut cts = Vec::new();
    let mut sample_flags = Vec::new();
    for position in 0..count {
        if flags & 0x100 != 0 {
            durations.push(u32::from_be_bytes([rest[0], rest[1], rest[2], rest[3]]));
            rest = &rest[4..];
        } else {
            durations.push(0);
        }
        if flags & 0x200 != 0 {
            sizes.push(u32::from_be_bytes([rest[0], rest[1], rest[2], rest[3]]));
            rest = &rest[4..];
        }
        if flags & 0x400 != 0 {
            sample_flags.push(u32::from_be_bytes([rest[0], rest[1], rest[2], rest[3]]));
            rest = &rest[4..];
        } else {
            // No per-sample flags: the first entry carries `first_sample_flags`
            // and later ones fall back to the tfhd defaults, which this writer
            // leaves unset (and unset flags are not sync).
            sample_flags.push(if position == 0 {
                first_flags.unwrap_or(0)
            } else {
                0
            });
        }
        if flags & 0x800 != 0 {
            cts.push(i32::from_be_bytes([rest[0], rest[1], rest[2], rest[3]]) as i64);
            rest = &rest[4..]; // composition offset (signed, trun version 1)
        } else {
            cts.push(0);
        }
    }
    assert!(rest.is_empty(), "trun entries account for every byte");
    Traf {
        tfdt_base,
        trun_count: count,
        trun_durations: durations,
        trun_sizes: sizes,
        trun_cts: cts,
        trun_flags: sample_flags,
    }
}

/// Pull every fragment a stream will answer with, in order.
fn drain_fragments(stream: &mut FragmentStream) -> Vec<Vec<u8>> {
    let mut fragments = Vec::new();
    loop {
        match stream
            .next_fragment()
            .expect("no error from a healthy stream")
        {
            Some(fragment) => fragments.push(fragment),
            None => return fragments,
        }
    }
}

/// The body bytes of one moof box, re-framed so `read_first_traf` (which wants
/// a whole fragment starting at the moof) can read it.
fn entry_body(_fragment: &[u8], entry: &Mp4Box<'_>) -> Vec<u8> {
    // Rebuild the moof as a standalone fragment: the box bytes exactly as they
    // appear, with no mdat, which read_first_traf never looks at.
    let size = entry.body.len() + 8;
    let mut out = Vec::with_capacity(size);
    out.extend_from_slice(&(size as u32).to_be_bytes());
    out.extend_from_slice(&entry.kind);
    out.extend_from_slice(entry.body);
    out
}

/// Every `moof` in every Vec a stream handed back: the first Vec carries the
/// init segment ahead of its fragment, and `finish` can return two fragments
/// in one Vec.
fn all_moofs(fragments: &[Vec<u8>]) -> Vec<Traf> {
    let mut out = Vec::new();
    for fragment in fragments {
        for entry in boxes(fragment) {
            if &entry.kind == b"moof" {
                out.push(read_first_traf(&entry_body(fragment, &entry)));
            }
        }
    }
    out
}

/// The total samples across every moof: what a `SourceBuffer` counts.
fn streamed_sample_count(fragments: &[Vec<u8>]) -> usize {
    all_moofs(fragments)
        .iter()
        .map(|traf| usize::try_from(traf.trun_count).expect("trun count fits usize"))
        .sum()
}

/// Every sample the stream handed back, rebuilt from the fragments: PTS is the
/// `tfdt` base plus the `trun` durations ahead of the entry plus the entry's
/// composition offset, minus the plan's offset the writer bakes into wire
/// times; duration and sync flag are the `trun`'s own words; the bytes are the
/// `mdat` that follows its moof, split by the `trun` sizes. This is the same
/// timeline identity `remux_video_from_start` checks in aggregate, row by row,
/// so the parity tests can compare bytes and flags against the demuxer's own
/// frame stream and not just totals.
fn streamed_samples(fragments: &[Vec<u8>]) -> Vec<Sample> {
    let timescale = init_timescale(fragments);
    let offset_ticks =
        i64::try_from(TIME_OFFSET_MS * u64::from(timescale) / 1_000).expect("the offset in ticks");
    let mut out = Vec::new();
    for fragment in fragments {
        let entries = boxes(fragment);
        let mut index = 0;
        while index < entries.len() {
            if &entries[index].kind != b"moof" {
                index += 1;
                continue;
            }
            assert!(index + 1 < entries.len(), "a moof is followed by its mdat");
            let mdat = entries[index + 1].body;
            let traf = read_first_traf(&entry_body(fragment, &entries[index]));
            assert_eq!(
                usize::try_from(traf.trun_sizes.iter().sum::<u32>()).expect("sizes fit usize"),
                mdat.len(),
                "the trun's sizes describe exactly its mdat"
            );
            let mut dts = i64::try_from(traf.tfdt_base).expect("tfdt fits i64");
            let mut cursor = 0usize;
            for position in 0..traf.trun_count as usize {
                let size =
                    usize::try_from(traf.trun_sizes[position]).expect("a sample size fits usize");
                out.push(Sample {
                    pts: dts + traf.trun_cts[position] - offset_ticks,
                    dts: None,
                    duration: Some(traf.trun_durations[position]),
                    keyframe: traf.trun_flags[position] & 0x0200_0000 == 0x0200_0000,
                    data: mdat[cursor..cursor + size].to_vec(),
                });
                cursor += size;
                dts += i64::from(traf.trun_durations[position]);
            }
            index += 2;
        }
    }
    out
}

/// The first frame `matroska-demuxer`'s own seek finds on `track` that is a
/// keyframe: the landing our source is built on, asked of the library.
fn oracle_first_keyframe(bytes: &[u8], track: u64, start_units: Option<u64>) -> Option<Frame> {
    let cursor = Cursor::new(bytes.to_vec());
    let mut file = MatroskaFile::open(cursor).expect("the demuxer opens its own fixture");
    if let Some(start) = start_units {
        file.seek(start).expect("the demuxer seeks");
    }
    let mut frame = Frame::default();
    loop {
        if !file
            .next_frame(&mut frame)
            .expect("no error from a healthy file")
        {
            return None;
        }
        if frame.track == track && frame.is_keyframe == Some(true) {
            return Some(frame);
        }
    }
}

/// The library's frame stream for `bytes`, seeked to `start_units` when given
/// and filtered to one track: the stream our source sits on, asked the same
/// question, answered by the demuxer rather than restated in the test.
fn oracle_stream(bytes: &[u8], track: u64, start_units: Option<u64>) -> Vec<Frame> {
    let cursor = Cursor::new(bytes.to_vec());
    let mut file = MatroskaFile::open(cursor).expect("the demuxer opens its own fixture");
    if let Some(start) = start_units {
        // A seek to zero is not a no-op in this library, and our source does
        // not seek at zero either: ask the demuxer the same question the
        // source was asked, which at zero means "read from the beginning".
        if start > 0 {
            file.seek(start).expect("the demuxer seeks");
        }
    }
    let mut out = Vec::new();
    let mut frame = Frame::default();
    while file
        .next_frame(&mut frame)
        .expect("no error from a healthy file")
    {
        if frame.track == track {
            out.push(frame.clone());
        }
    }
    out
}

/// The frames a video source keeps from a frame stream, with the sync flag
/// each one carries: everything from the first frame that is not known to be
/// a reference frame, with unknown flags counting as sync until a real
/// keyframe anchors the timeline, after which only flagged-key frames are
/// sync. The crate's documented reading, restated in test code so the
/// comparison is against a second implementation and not itself.
fn source_kept_video(frames: &[Frame]) -> Vec<(bool, &Frame)> {
    let mut anchored = false;
    let mut out: Vec<(bool, &Frame)> = Vec::new();
    for frame in frames {
        let sync = match (frame.is_keyframe, anchored) {
            (Some(true), _) => true,
            (Some(false), false) => continue,
            (Some(false), true) => false,
            (None, false) => true,
            (None, true) => false,
        };
        anchored |= sync;
        out.push((sync, frame));
    }
    out
}


/// One fixture track's `expected.json` entry.
fn expected_track_entry(name: &str, track: u32) -> Value {
    let path = fixture_path("expected.json");
    let text = std::fs::read_to_string(path).expect("expected.json");
    let json: Value = serde_json::from_str(&text).expect("expected.json is JSON");
    json["fixtures"]
        .get(name)
        .unwrap_or_else(|| panic!("expected.json has no {name}"))
        .get("tracks")
        .and_then(Value::as_array)
        .expect("a tracks array")
        .iter()
        .find(|entry| entry.get("expect_id").and_then(Value::as_u64) == Some(u64::from(track)))
        .cloned()
        .unwrap_or_else(|| panic!("expected.json has no track {track} in {name}"))
}

/// The track's frame count, ffprobe's packet count for it.
fn expected_frame_count(name: &str, track: u32) -> usize {
    expected_track_entry(name, track)
        .get("frame_count")
        .and_then(Value::as_u64)
        .expect("a frame count") as usize
}

/// The first entry of the track's keyframe PTS list at or after `from_ms`.
fn expected_first_keyframe_ms(name: &str, track: u32, from_ms: i64) -> i64 {
    expected_track_entry(name, track)
        .get("keyframe_pts_ms")
        .and_then(Value::as_array)
        .expect("a keyframe list")
        .iter()
        .filter_map(Value::as_i64)
        .filter(|ms| *ms >= from_ms)
        .min()
        .expect("a keyframe at or after the start time")
}


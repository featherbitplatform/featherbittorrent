//! Task 3: opening one Matroska track and streaming it as fragmented MP4.
//!
//! The tests below check the two things Task 3 promises. First, that the
//! samples the source hands over are the container's own: same bytes, same
//! timestamps, same keyframe decisions, at the sync point a seek should land
//! on - so `matroska-demuxer` reading the same file through its own `seek` and
//! `next_frame` serves as the independent oracle for every PTS claim. Second,
//! that the fragments are real fragmented MP4: a box walk with `mp4_atom`
//! conventions reading the headers, and manual reads of the fields a player
//! depends on - `tfdt`'s base media decode time and `trun`'s sample count,
//! durations, composition offsets and sync flags - read field by field rather
//! than through a model that could be as wrong as the writer.
//!
//! Frame counts and keyframe lists are read from `expected.json`, ffprobe's
//! own view of each fixture, so a fixture regenerated by
//! `dev/make-media-fixtures.sh` moves the tests with it.
//!
//! Two measured facts about the fixtures shape the seek tests. The main
//! fixture's cue table is junk the demuxer trusts: its cue positions point
//! past the end of the file, so *any* nonzero seek - the library's own and
//! ours alike - lands the reader beyond the last cluster; `remux_audio_track_from_midsecond_start`
//! asserts that directly, and the keyframe landing the brief describes is
//! checked on the in-memory GOP file (same 1 s keyframe pattern as the
//! fixture, a layout the cluster walk can follow) and on the real cue-less
//! fixture. And the library's seek lands on the first block at or after the
//! target and never rewinds, so a keyframe just below the seek point is
//! already behind the reader when the source opens: from 1500 ms that means
//! the stream starts at the keyframe at 2000 ms, and `expected.json`'s first
//! keyframe at or after 1500 is 2000, so the two readings name the same frame
//! on these fixtures.
//!
//! The hostile-file tests build their inputs in memory: a cue pointing past
//! the end, an element size that overruns the stream, a cluster table with 60k
//! entries. The demuxer panics on two of those shapes in a debug build, and a
//! panic in a library reading remote input is a crashed API worker, so the
//! crate wraps it: those tests assert the panic arrives as a `Malformed`
//! verdict (or, for the cue, as a stream that ends cleanly), never as a panic
//! and never as a hang.

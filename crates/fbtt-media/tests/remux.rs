#[test]
fn remux_unsupported_codec_is_unsupported() {
    // VP9: a browser demuxes VP9 from WebM natively (plan ruling 3), so there
    // is no fragmented-MP4 sample entry fbtt writes for it and the real VP9
    // fixture is refused at open. And a track type that holds no media - a
    // logo track - has no samples to remux whatever its codec says. Both
    // refusals arrive naming the track, at open. (Subtitles are
    // remux_refuses_subtitles_and_unknown_track's.)
    let error = open_track(Cursor::new(fixture_bytes(WEBM)), 1, 0)
        .expect_err("VP9 has no fragmented-MP4 sample entry fbtt writes");
    assert!(
        matches!(error, MediaError::Unsupported(_)),
        "VP9 is Unsupported: {error:?}"
    );
    let tracks = ebml(
        &TRACKS,
        &[ebml(
            &TRACK_ENTRY,
            &[
                ebml(&TRACK_NUMBER, &[1]),
                ebml(&TRACK_UID, &[11]),
                ebml(&TRACK_TYPE, &[7]), // logo: a track type that holds no media
                ebml(&CODEC_ID, VP9_ID),
            ]
            .concat(),
        )]
        .concat(),
    );
    let clusters = vec![cluster(0, &[simple_block(1, 0, true, &[0x01])])];
    let file = matroska_file(&indexed_segment(&tracks, 1_000_000, &clusters));
    match open_track(Cursor::new(file), 1, 0).expect_err("a logo track has no samples to remux") {
        MediaError::Unsupported(message) => assert!(
            message.contains("track 1"),
            "the refusal names what is missing: {message}"
        ),
        other => panic!("a logo track is Unsupported, got {other:?}"),
    }
}

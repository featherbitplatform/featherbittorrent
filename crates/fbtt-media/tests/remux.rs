/// A keyframe, five `BlockGroup`s that hold no `Block`, then a second frame:
/// the demuxer reports every one of those empties as a read block without
/// filling its frame slot, so without a "was the slot filled at all" check the
/// stale keyframe is emitted again and again - seven samples for two frames,
/// five of them empty sync frames. And 100 001 empties after one keyframe are
/// 100 001 frame reads that delivered nothing: they count against the walk
/// bound, which is what turns them into a `Malformed` give-up inside five
/// seconds instead of a 400 KB file's worth of nothing.
#[test]
fn remux_empty_block_groups_are_skipped() {
    let tracks = ebml(
        &TRACKS,
        &[track_element(
            1,
            1,
            H264_ID,
            Some(avcc().as_slice()),
            None,
            Some((640, 360)),
            None,
            None,
        )]
        .concat(),
    );
    let blocks = |extra: &[Vec<u8>]| -> Vec<Vec<u8>> {
        let mut blocks = vec![simple_block(1, 0, true, &[0x41, 0x01])];
        blocks.extend_from_slice(extra);
        blocks
    };

    let file = {
        let empties = vec![empty_block_group(); 5];
        let mut inner = blocks(&empties);
        inner.push(simple_block(1, 40, false, &[0x41, 0x02]));
        let clusters = vec![cluster(0, &inner)];
        matroska_file(&indexed_segment(&tracks, 1_000_000, &clusters))
    };
    let mut stream = open_track(Cursor::new(file), 1, 0).expect("opens");
    let fragments = drain_fragments(&mut stream);
    let samples = streamed_samples(&fragments);
    assert_eq!(samples.len(), 2, "five empty BlockGroups made no samples");
    assert_eq!(&samples[0].data, &[0x41, 0x01], "the keyframe's own bytes");
    assert_eq!(
        &samples[1].data,
        &[0x41, 0x02],
        "the second frame's own bytes"
    );
    assert!(samples[0].keyframe, "the keyframe starts the stream");
    assert!(
        !samples[1].keyframe,
        "the unflagged second frame is non-sync after the anchor"
    );

    // The bound direction. 100 001 empties after one keyframe, in a thread so
    // a hang (the mutation's failure mode is streaming 200k bytes forever
    // more) would be a timeout, not an infinite wait.
    let file = {
        let empties = vec![empty_block_group(); 100_001];
        let clusters = vec![cluster(0, &blocks(&empties))];
        matroska_file(&indexed_segment(&tracks, 1_000_000, &clusters))
    };
    let (sender, receiver) = std::sync::mpsc::channel();
    thread::spawn(move || {
        let mut stream = open_track(Cursor::new(file), 1, 0).expect("the header is fine");
        let verdict = loop {
            match stream.next_fragment() {
                Ok(Some(_)) => {}
                Ok(None) => break "clean end of stream".to_string(),
                Err(error) => break error.to_string(),
            }
        };
        let _ = sender.send(verdict);
    });
    let verdict = match receiver.recv_timeout(Duration::from_secs(5)) {
        Ok(verdict) => verdict,
        Err(std::sync::mpsc::RecvTimeoutError::Timeout) => {
            panic!("a stream of empty BlockGroups hung instead of giving up")
        }
        Err(std::sync::mpsc::RecvTimeoutError::Disconnected) => {
            panic!("the walk panicked instead of reporting a verdict")
        }
    };
    assert!(
        verdict.contains("malformed"),
        "100 001 empty BlockGroups after one keyframe answered {verdict:?}, not a Malformed give-up"
    );
}

/// An MP3 track with `DefaultDuration` whose blocks are fixed-laced groups of
/// four frames: the demuxer reports all four frames of a block with the
/// block's single timestamp, so an unspaced source serves PTS
/// `[0, 0, 0, 0, ...]` and the writer, finding no decode gap, endows three of
/// the four samples with one-tick durations. The i-th frame of a
/// same-timestamp run plays `i * DefaultDuration` later; the PTS rows below
/// are checked against that arithmetic exactly, in the track's own ticks.
#[test]
fn remux_laced_audio_gets_spaced_timestamps() {
    // DefaultDuration 25 ms: at 44.1 kHz that is 1102.5 ticks, so the exact
    // PTS the spacing produces is floor(ms * 44100 / 1000) per frame and the
    // gaps alternate 1102 and 1103 - no duration anywhere is the writer's 1
    // tick of desperation.
    let default_duration_ns: u64 = 25_000_000;
    let tracks = ebml(
        &TRACKS,
        &[track_element(
            2,
            2,
            MP3_ID,
            None,
            Some((44100.0, 2)),
            None,
            Some(default_duration_ns),
            None,
        )]
        .concat(),
    );
    let clusters = vec![cluster(
        0,
        &[
            laced_simple_block(2, 0, 4, 33),
            laced_simple_block(2, 100, 4, 33),
            laced_simple_block(2, 200, 4, 33),
        ],
    )];
    let file = matroska_file(&indexed_segment(&tracks, 1_000_000, &clusters));

    let mut stream = open_track(Cursor::new(file), 2, 0).expect("the laced MP3 track opens");
    let fragments = drain_fragments(&mut stream);
    let samples = streamed_samples(&fragments);
    assert_eq!(samples.len(), 12, "twelve frames, twelve samples");
    for (position, sample) in samples.iter().enumerate() {
        // The frame's place in its block, and the block's timecode: PTS is
        // the block timestamp plus index times DefaultDuration, in source
        // nanoseconds, truncated to track ticks exactly as the source does.
        let frame_in_block = u64::try_from(position % 4).expect("a frame index");
        let block_ms = 100 * u64::try_from(position / 4).expect("a small block index");
        let pts_ns = block_ms * 1_000_000 + frame_in_block * default_duration_ns;
        let expected = i64::try_from(pts_ns * 44_100 / 1_000_000_000).expect("a small PTS");
        assert_eq!(
            sample.pts, expected,
            "frame {position} plays at its block's timestamp plus its index times DefaultDuration"
        );
        assert_ne!(
            sample.duration,
            Some(1),
            "frame {position} sits on its own timeline gap, not a borrowed tick"
        );
    }
}

/// A reader that starts timing out mid-stream answers `Io` the first time and
/// keeps answering `Io`: the plan says a remote reader changes the answer and
/// never the verdict's kind, and a `TimedOut` piece that has not arrived is a
/// claim about the reader on call one and on call two alike. The old behaviour
/// degraded every later call to `Malformed("io: ...")`, which tells a caller
/// to give up on a file that a retry would finish.
#[test]
fn remux_io_error_stays_io() {
    let file = fixture_bytes(MKV);
    // The limit sits mid-cluster: measured on this fixture, the header read
    // and the first fragments pass at 85% of the file, and a later block body
    // read is what crosses the line. (A failure while the demuxer walks
    // *between* elements is its own end-of-stream, so the cut has to land
    // inside data.)
    let limit = u64::try_from(file.len()).expect("a fixture size") * 85 / 100;
    let reader = TimesOutAfter {
        inner: Cursor::new(file),
        remaining: limit,
    };
    let mut stream = open_track(reader, 1, 0).expect("the header is inside the limit");
    let first = loop {
        match stream.next_fragment() {
            Ok(Some(fragment)) => assert!(!fragment.is_empty(), "fragments carry bytes"),
            Ok(None) => panic!("a stream whose reader was cut off ended cleanly"),
            Err(error) => break error,
        }
    };
    match &first {
        MediaError::Io(error) => assert_eq!(
            error.kind(),
            ErrorKind::TimedOut,
            "the cut answers as the timeout it is",
        ),
        other => panic!("the cut answered {other:?}, not an Io verdict"),
    }
    // And every later call repeats the same kind: a reader that is still
    // timing out is still a reader that is timing out, not a file that
    // changed what it is between two questions.
    match stream.next_fragment() {
        Err(MediaError::Io(error)) => assert_eq!(
            error.kind(),
            ErrorKind::TimedOut,
            "the replay keeps the timeout's kind",
        ),
        Err(other) => panic!("the replay degraded {first:?} into {other:?}"),
        Ok(other) => panic!("the replay answered Ok({other:?}) after an Io verdict"),
    }
}


//! Task 3 and Task 4: opening one track and streaming it as fragmented MP4.
//!
//! The tests below check the two things those tasks promise, through the crate's
//! public door only - `open_track` and `FragmentStream`, exactly what the
//! server and the page see. First, that the samples the fragments carry are
//! the container's own: same bytes, same timestamps, same keyframe decisions,
//! at the sync point a seek should land on - so `matroska-demuxer` reading a
//! Matroska file through its own `seek` and `next_frame`, and a fixture's own
//! sample tables read through `mp4-atom`, serve as the independent oracle for
//! every PTS claim. Second, that the fragments are real fragmented
//! MP4: the sample rows below are rebuilt from the bytes a player receives -
//! `tfdt`'s base media decode time and `trun`'s per-sample durations, sizes,
//! composition offsets and sync flags - read field by field rather than
//! through a model that could be as wrong as the writer.
//!
//! One test cannot be asked through the public door: `BlockDuration`'s stated
//! duration reaches a `Sample` but only the last sample of a stream carries a
//! stated duration on the wire, so `remux_blockgroup_first_frame_counts_as_sync`
//! lives as a unit test inside `src/mkv.rs` under the same name. Everything
//! here uses `open_track` and `FragmentStream` and decodes the output itself.
//!
//! Frame counts and keyframe lists are read from `expected.json`, ffprobe's
//! own view of each fixture, so a fixture regenerated by
//! `dev/make-media-fixtures.sh` moves the tests with it.
//!
//! One measured fact about the fixtures shapes the audio seek tests. The
//! main fixture's cue table is ffmpeg's: entries for the video keyframes
//! only (plus two for a subtitle track), each pointing into its cluster's
//! bytes. The seek follows a cue into the cluster and the walk then collects
//! every block from the landing on, in file order - and among them the audio
//! frames that trail the cue point in file order but sit before the target
//! in time are still in the reader's way, which is what the source's
//! pre-start filter is for: `remux_audio_track_from_midsecond_start`
//! asserts the landings (against the fixture's own cluster timecodes, 0,
//! 801, 1801 and 2816 ms) and `remux_audio_drops_frames_before_start`
//! builds the cue-before-start shape in memory. And the library's seek
//! lands on the first block at or after the target and never rewinds, so a
//! keyframe just below the seek point is already behind the reader when the
//! source opens: from 1500 ms that means the video stream starts at the
//! keyframe at 2000 ms, and `expected.json`'s first keyframe at or after
//! 1500 is 2000, so the two readings name the same frame - on the fixture
//! itself (`remux_seek_starts_on_a_keyframe`) and on the cue-less GOP file
//! (`remux_seek_starts_on_a_keyframe_in_synthetic_gops`).
//!
//! The hostile-file tests build their inputs in memory: a cue with a
//! hostile `CueRelativePosition`, an element size that overruns the stream,
//! a cluster table with 60k entries, empty `BlockGroup`s, a reader that
//! stops timing out mid-stream. The demuxer's upstream did panic on two of
//! those shapes in a debug build; the pinned featherbit fork overflow-checks
//! that arithmetic, and the crate keeps its own catch-unwind guard too,
//! because a panic in a library reading remote input is a crashed API
//! worker: those tests assert the panic arrives as a `Malformed` verdict
//! (or, for the cue, as a stream that ends with nothing to play), never as
//! a panic and never as a hang.

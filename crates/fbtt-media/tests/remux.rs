        oracle_first_keyframe(&file, 1, Some(1500)).expect("a keyframe at or after 1500");
    assert_eq!(
        i64::try_from(expected.timestamp).expect("a small timestamp"),
        expected_ms,
        "the GOP file's landing matches the fixture's expected.json keyframe list"
    );
    assert_eq!(
        u64::try_from(expected_ms).expect("a small start time"),
        stream.start_ms(),
        "the stream starts at the first keyframe at or after the seek point, not at 1500"
    );

    // tfdt = source PTS + the plan's 1000 ms, in track ticks, and the first
    // sample is sync.
